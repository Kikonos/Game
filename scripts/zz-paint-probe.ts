import { newGame, run, offer } from '../src/engine/contracts/testkit';
import { acceptOffer, feasibility } from '../src/engine/contracts';
import { liveryOf, paintStatus } from '../src/engine/ops';
import { DAY, fmtDateTime } from '../src/engine/core/time';
const g = newGame(7);
const o = offer(g, 'seasonBase', { airport: 'HAM', dests: ['PMI'], start: g.now + 40 * DAY, days: 60, paint: { kind: 'full', required: true } });
console.log(o.paint, o.blurb);
const ac = Object.values(g.fleet)[0];
const rep = feasibility(g, o.id, ac.id);
console.log(rep.checks.filter(c => c.id === 'paint' || c.level !== 'ok'), rep.paint && fmtDateTime(rep.paint.start), rep.estCost, rep.estRevenue);
console.log(feasibility(g, o.id, ac.id, { paint: false }).checks.find(c => c.id === 'paint'));
const r = acceptOffer(g, o.id, [ac.id]);
console.log(r);
const c = g.contracts[r.ok ? r.data!.contractId : ''];
console.log(c.paint?.inMx, Object.values(g.maintenance).map(m => [m.kind, m.at, fmtDateTime(m.start), fmtDateTime(m.end), m.cost, m.paint]));
console.log(paintStatus(g, ac.id));
run(g, c.start);
console.log('at start', ac.paintedFor, liveryOf(g, ac).source, liveryOf(g, ac).name, g.finance.current.lines.paint, g.finance.receivables.filter(x => x.desc.startsWith('Paint')).map(x => x.amount));
run(g, c.end + 20 * DAY);
console.log('after', c.status, ac.paintedFor, liveryOf(g, ac).source, Object.values(g.maintenance).filter(m => m.kind === 'paint').map(m => [m.status, m.paint?.phase, fmtDateTime(m.start), m.at]));
console.log(g.messages.filter(m => /colours|Paint|Repaint/.test(m.title)).map(m => `${m.title} | ${m.body}`));
console.log(g.finance.history.map(h => h.lines.paint ?? 0), g.finance.current.lines.paint);
